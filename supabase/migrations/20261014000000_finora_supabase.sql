create table if not exists public.users (
    id bigint generated by default as identity primary key,
    auth_user_id uuid not null unique references auth.users(id) on delete cascade,
    name varchar(120) not null,
    email varchar(190) not null unique,
    pending_email varchar(190) unique,
    email_verified_at timestamptz,
    legacy_mysql_id bigint unique,
    created_at timestamptz not null default now()
);

create table if not exists public.transactions (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    type text not null check (type in ('income', 'expense')),
    merchant varchar(160) not null,
    category varchar(80) not null,
    amount numeric(12,2) not null,
    transaction_date date not null,
    transaction_time time,
    payment_method text check (payment_method is null or payment_method in ('cash', 'upi', 'credit_card', 'debit_card', 'wallet', 'bank_transfer')),
    location varchar(160),
    notes varchar(500),
    category_confidence numeric(5,2),
    source varchar(24) not null default 'manual',
    created_at timestamptz not null default now()
);
create index if not exists idx_transactions_user_date on public.transactions(user_id, transaction_date);
create index if not exists idx_transactions_user_day on public.transactions(user_id, transaction_date, transaction_time);

