create or replace function public.finora_user_id()
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
    select id from public.users where auth_user_id = auth.uid() limit 1
$$;
revoke all on function public.finora_user_id() from public, anon, authenticated;

create or replace function public.handle_new_supabase_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    app_user_id bigint;
begin
    insert into public.users (auth_user_id, name, email, email_verified_at)
    values (
        new.id,
        coalesce(nullif(new.raw_user_meta_data ->> 'name', ''), split_part(new.email, '@', 1)),
        new.email,
        new.email_confirmed_at
    )
    on conflict (auth_user_id) do update
    set email = excluded.email,
        email_verified_at = excluded.email_verified_at
    returning id into app_user_id;

    insert into public.financial_profile (user_id)
    values (app_user_id)
    on conflict (user_id) do nothing;
    return new;
end;
$$;

drop trigger if exists on_auth_user_finora_profile on auth.users;
create trigger on_auth_user_finora_profile
after insert or update on auth.users
for each row execute function public.handle_new_supabase_user();

